"""The shipped settings table: every setting, its default and its meaning.

The JSON is generated by ``tools/gen_settings_table.py`` from the gschema and
the code's own consent sets. This module only loads it: no GTK, no Gio, no
keyring, so a terminal, the engine and the tests all read the same table with
the same interpreter and the same defaults.

Run ``python3 tools/gen_settings_table.py`` after changing a schema default or
the person's decision; the table is data, not a second place to keep a list.
"""

from __future__ import annotations

import json
from pathlib import Path

# settings_table.py lives at usr/lib/shani-chronoa/shani_chronoa/, so the
# shipped file is three parents up, then share/shani-chronoa/settings.json.
_TABLE_PATH = (
    Path(__file__).resolve().parents[3] / "share" / "shani-chronoa" / "settings.json"
)

with _TABLE_PATH.open(encoding="utf-8") as _handle:
    _DATA = json.load(_handle)

TABLE: dict[str, dict] = _DATA["settings"]
DEFAULTS: dict[str, object] = {key: row["default"] for key, row in TABLE.items()}
KEYS: tuple[str, ...] = tuple(sorted(TABLE))


def default_for(key: str):
    """The shipped default. Unknown keys raise, as they should."""
    return DEFAULTS[key]


def label(key: str) -> str:
    return TABLE[key]["label"]


def kind(key: str) -> str:
    """The schema type code: ``b``, ``d`` or ``s``."""
    return TABLE[key]["type"]


def flags(key: str) -> dict:
    """``consent``, ``destructive`` and ``secret`` for one key."""
    row = TABLE[key]
    return {
        "consent": row["consent"],
        "destructive": row["destructive"],
        "secret": row["secret"],
    }
