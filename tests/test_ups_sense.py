# --- what is NOT read -----------------------------------------------------


def test_the_credential_file_is_never_read(sense, tmp_path, monkeypatch):
    """upsd.users holds the credential that can force a UPS power-down. Reading
    it into a percept would put it in an LLM prompt."""
    reads = []
    real_open = open

    def spy(path, *a, **k):
        if "upsd.users" in str(path):
            reads.append(str(path))
        return real_open(path, *a, **k)

    monkeypatch.setattr("builtins.open", spy)
    _sysfs(tmp_path / "ps")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "no-such-upsmon.conf")
    _answer(sense)
    assert not reads, reads


def test_the_device_section_is_not_reported(sense, tmp_path, monkeypatch):
    """Which port and driver the hardware uses is not a fact worth sending to a
    model, and it is the part nut-scanner writes."""
    _sysfs(tmp_path / "ps")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "no-such-upsmon.conf")
    text = _answer(sense)
    assert "upsd.users" not in text


# --- upsc parsing ---------------------------------------------------------


def test_upsc_values_containing_colons_survive_the_split():
    """`ups.mfr: American Power Conversion` has a colon in the value, and
    splitting on every colon keeps only its first field."""
    parsed = up._parse_upsc("ups.mfr: American Power Conversion\nbattery.charge: 100\n")
    assert parsed["ups.mfr"] == "American Power Conversion"
    assert parsed["battery.charge"] == "100"


def test_upsc_output_is_parsed_into_the_percept(sense, tmp_path, monkeypatch):
    _sysfs(tmp_path / "ps", online=0, status="OB DISCHRG")
    monkeypatch.setattr(up, "_resolve", lambda b: "/usr/bin/upsc")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "upsmon.conf")
    (tmp_path / "upsmon.conf").write_text(UPS_LINE)
    monkeypatch.setattr(up, "_read_upsc",
                        lambda u, n: "OK:ups.status: OB LB\nbattery.charge: 12\n"
                                    "battery.runtime: 300\nups.load: 25\n")
    text = _answer(sense)
    assert "ON BATTERY" in text
    assert "mains is out" in text
    assert "battery.charge: 12" in text
    assert "battery.runtime: 300" in text


def test_an_empty_but_successful_upsc_is_not_a_failure():
    """The "OK:" prefix makes an empty read distinguishable from an error, and a
    bare empty string would have been read as failure."""
    assert up._parse_upsc("") == {}


def test_the_monitor_name_is_what_upsc_is_asked_for(sense, tmp_path, monkeypatch):
    """The MONITOR line's system is `<name>@<host>` and upsc needs the bare name.
    Asking it for the whole string fails silently."""
    _sysfs(tmp_path / "ps")
    monkeypatch.setattr(up, "_resolve", lambda b: "/usr/bin/upsc")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "upsmon.conf")
    (tmp_path / "upsmon.conf").write_text(UPS_LINE)
    asked = []
    monkeypatch.setattr(up, "_read_upsc", lambda u, n: asked.append(n) or "OK:x: 1")
    _answer(sense)
    assert asked == ["myups"]


def test_a_refused_upsc_is_reported_not_swallowed(sense, tmp_path, monkeypatch):
    _sysfs(tmp_path / "ps")
    monkeypatch.setattr(up, "_resolve", lambda b: "/usr/bin/upsc")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "upsmon.conf")
    (tmp_path / "upsmon.conf").write_text(UPS_LINE)
    monkeypatch.setattr(up, "_read_upsc", lambda u, n: "upsc refused: Driver not connected")
    text = _answer(sense)
    assert "could not be read" in text
    assert "Driver not connected" in text


def test_a_commented_monitor_line_is_not_a_monitored_ups(sense, tmp_path, monkeypatch):
    """The shipped file's MONITOR line is commented out between markers, so a
    machine right after install has a policy and nothing to apply it to."""
    _sysfs(tmp_path / "ps")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "upsmon.conf")
    (tmp_path / "upsmon.conf").write_text(NO_MONITOR)
    assert up._monitor_name() is None
    # sysfs still answers, even with nothing monitored - that half needs no NUT.
    text = _answer(sense)
    assert "on mains" in text or "ON BATTERY" in text


