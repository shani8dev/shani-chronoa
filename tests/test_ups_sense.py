def test_consent_off_is_refused_by_name(sense):
    out = sense.run({})
    text = out.text if hasattr(out, "text") else str(out)
    if "turned off" not in text:
        pytest.skip("consent is granted here; the refusal path is covered by the "
                    "shared consent suite")
    assert "ups-sense-enabled" in text


def test_sysfs_and_upsc_disagreeing_is_said_not_resolved_silently(
        sense, tmp_path, monkeypatch):
    """The kernel's driver and NUT's daemon can disagree, and picking one without
    saying so is how a machine on mains comes to be reported as on battery.

    sysfs `online=1` with upsc `ups.status: OB` is exactly this. The sense reports
    the daemon's answer - it is the one actually talking to the hardware - but it
    names the disagreement, because a reader told only one of the two has no way
    to know the other was ever consulted.
    """
    _sysfs(tmp_path / "ps", online=1, status="OL")
    monkeypatch.setattr(up, "_GLOB", tmp_path / "ps/*")
    monkeypatch.setattr(up, "_UPSMON_CONF", tmp_path / "upsmon.conf")
    (tmp_path / "upsmon.conf").write_text(UPS_LINE)
    monkeypatch.setattr(up, "_resolve", lambda b: "/usr/bin/upsc")
    monkeypatch.setattr(up, "_read_upsc",
                        lambda u, n: "OK:ups.status: OB\nbattery.charge: 88\n")
    text = _answer(sense)
    assert "mains is out" in text          # the daemon's answer wins
    assert "disagree" in text              # ...and the disagreement is named
    assert "battery.charge: 88" in text
