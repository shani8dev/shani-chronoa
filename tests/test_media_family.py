# --- edit_video ---------------------------------------------------------------

@pytest.mark.skipif(not _needs_ffmpeg(), reason="ffmpeg/ffprobe are not installed")
def test_speeding_up_a_video_changes_its_duration(video, home):
    """The effect has to be real: the output's duration is read back with
    ffprobe rather than trusted from ffmpeg's exit code.
    """
    out_path = home / "faster.mp4"
    out = EV._run({"path": str(video), "speed": 2.0, "output": str(out_path)})
    assert out_path.exists(), out
    # Read the result back: a 1-second file at 2x is about half a second.
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                        "-of", "default=nw=1:nk=1", str(out_path)],
                       capture_output=True, text=True, timeout=60)
    duration = float(r.stdout.strip())
    assert 0.3 <= duration <= 0.75, f"2x speed of 1s should be ~0.5s, got {duration}"


@pytest.mark.skipif(not _needs_ffmpeg(), reason="ffmpeg/ffprobe are not installed")
def test_a_combining_of_incompatible_flags_is_refused(video, home):
    """An unsupported combination is refused rather than half-applied."""
    out = EV._run({"path": str(video), "speed": 99.0, "output": str(home / "x.mp4")})
    assert "Speed must be between" in out, out
    assert not (home / "x.mp4").exists()


@pytest.mark.skipif(not _needs_ffmpeg(), reason="ffmpeg/ffprobe are not installed")
def test_a_missing_ffmpeg_is_a_missing_binary(monkeypatch, video, home):
    monkeypatch.setattr(EV.shutil, "which", lambda b: None)
    out = EV._run({"path": str(video), "speed": 2.0, "output": str(home / "x.mp4")})
    assert "ffmpeg" in out
    assert "not installed" in out
    assert not (home / "x.mp4").exists()
