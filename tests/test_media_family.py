# --- read_image ---------------------------------------------------------------

def test_a_real_picture_reports_its_dimensions_and_format(picture):
    """Pillow is optional like ffmpeg; when it is present the answer is real."""
    if RI._Image is None:
        pytest.skip("Pillow is not installed here")
